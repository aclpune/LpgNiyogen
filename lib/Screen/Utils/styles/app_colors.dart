  static const double dividerHigh   = 0.5;
  /// Divider at medium visibility (outline.withOpacity(0.4))
  static const double dividerMedium = 0.4;
  /// Hero badge background opacity (AddReturnItemXMI _ScreenHeader)
  static const double heroBadgeBg   = 0.18;
  /// Hero badge border opacity (AddReturnItemXMI _ScreenHeader)
  static const double heroBadgeBorder = 0.30;

  // ── SQC Register Screen ──────────────────────────────────
  /// Bottom-sheet modal: white overlay on hero vehicle badge. Was: withOpacity(0.18)
  static const double sqcHeroBadgeBg     = 0.18;
  /// Bottom-sheet modal: white icon-container background. Was: withOpacity(0.16)
  static const double sqcHeroIconBg      = 0.16;
  /// Hero icon container border. Was: withOpacity(0.28)
  static const double sqcHeroIconBorder  = 0.28;
  /// Defect upload card: red icon container background. Was: withOpacity(0.15)
  static const double sqcRedIconBg       = 0.15;
  /// Defect upload card: red border overlay. Was: withOpacity(0.3)
  static const double sqcRedBorder       = 0.3;


}


